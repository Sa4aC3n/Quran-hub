            }

            // Surah 2: Al-Baqarah
            2 -> when (ayahNumber) {
                1 -> "الم: حروف مقطعة افتتحت بها بعض السور للتحدي والإعجاز، وبيان أن هذا القرآن مؤلف من جنس الحروف التي يتكلم بها العرب ومع ذلك عجزوا عن الإتيان بمثله."
                2 -> "ذلك الكتاب العظيم وهو القرآن الكريم لا ريب فيه ولا شك أنه منزل من عند الله، هداية وإرشاد للمتقين الذين يخشون ربهم ويعملون بأمره."
                3 -> "الذين يصدقون بالغيب مما أخبر الله به ورسوله من الإيمان بالله والملائكة والكتب والرسل واليوم الآخر والقدر، ويؤدون الصلاة بأركانها وشروطها، ومما رزقناهم ينفقون في سبيل الله."
