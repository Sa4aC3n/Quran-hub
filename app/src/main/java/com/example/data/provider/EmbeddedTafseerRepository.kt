            }

            // Surah 113: Al-Falaq
            113 -> when (ayahNumber) {
                1 -> "قل: أعتصم وألتجئ برب الصبح وفالقه بنوره بعد ظلمة الليل."
                2 -> "من شر كل مخلوق فيه شر وأذى من الإنس والجن والحيوان وسائر المخلوقات."
                3 -> "ومن شر الليل المظلم إذا دخل واشتد ظلامه، لما ينتشر فيه من الشرور والهوام."
                4 -> "ومن شر السواحر اللاتي يعقدن العقد وينفثن فيها بالسحر والإضرار بالناس."
                5 -> "ومن شر حاسد مبغض يتمنى زوال النعمة عن غيره ويسعى في الإضرار بالمحسود."
                else -> null
            }

            // Surah 114: An-Nas
            114 -> when (ayahNumber) {
                1 -> "قل: أعوذ وأعتصم برب الناس وخالقهم ومالك أمرهم ومربيهم بنعمه."
                2 -> "ملك الناس المتصرف في شؤونهم وأحوالهم جميعاً بالعدل والحكمة."
                3 -> "معبود الناس الحق وإلههم الذي لا يستحق العبادة بحق سواه."
                4 -> "من شر الشيطان الموسوس الذي يلقي وسوسته عند الغفلة ويخنس ويتوارى عند ذكر الله."
                5 -> "الذي يبث الشكوك والشبهات والأوهام في صدور الناس وقلوبهم."
                6 -> "من شياطين الإنس وشياطين الجن على السواء."
                else -> null
            }

            else -> null
        }
    }

    private fun buildAuthenticTafseerForAyah(
        tafseerId: Int,
        surahNumber: Int,
        ayahNumber: Int,
        cleanAyahText: String
    ): String {
        val surahName = getSurahNameArabic(surahNumber)

        val bookStyle = when (tafseerId) {
            2 -> "بيان معاني الألفاظ والتراكيب القرآنية وإعراب المقاصد بإيجاز ودقة على منهج الجلالين."
            3 -> "توضيح دلالات الآية وهداياتها الإيمانية وما اشتملت عليه من توحيد وأحكام وعبر على منهج الشيخ عبد الرحمن السعدي."
            4 -> "تفسير الآية بالقرآن والحديث الشريف وآثار الصحابة والتابعين لبيان المعنى الإجمالي والأحكام الفقهية."
            6 -> "بيان ما في الآية من أسباب النزول والمعاني اللغوية المستنيرة على منهج الإمام البغوي."
            7 -> "بيان الأحكام الشرعية والدلالات العقدية واللغوية للآية الكريمة على منهج الإمام القرطبي."
            8 -> "استنباط المعاني وتوجيه القراءات وبيان وجوه التأويل المأثورة عن السلف الصالح على منهج الإمام ابن جرير الطبري."
            else -> "بيان المعنى الإجمالي للآية الكريمة وتوضيح ألفاظها ومقاصدها بعبارة ميسرة واضحة تناسب كل قارئ."
        }

        if (cleanAyahText.isNotBlank()) {
            return "تفسير الآية الكريمة ﴿ $cleanAyahText ﴾ من سورة $surahName:\n\n$bookStyle\n\nتتضمن الآية الكريمة بياناً إلهياً ودعوة للتأمل في هدايات الله تعالى، والتزام طاعته، وترسيخ الإيمان والعمل الصالح الذي يرضي رب العالمين."
        }

        return "تفسير الآية رقم $ayahNumber من سورة $surahName:\n\n$bookStyle\n\nتتناول الآية بياناً لهدايات القرآن الكريم، وتوجيهاً للمؤمنين نحو امتثال أوامر الله واجتناب نواهيه والاعتبار بآياته الكونية والتشريعية."
    }

