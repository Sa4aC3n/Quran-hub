                4 -> "إلا الذين عاهدتم من المشركين ثم لم ينقصوكم شيئاً من شروط العهد ولم يظاهروا عليكم أحداً من الأعداء، فأتموا إليهم عهدهم إلى مدتهم المحددة؛ إن الله يحب المتقين الموفين بالعهود."
                5 -> "فإذا انقضت الأشهر الحرم التي أُمّن فيها المشركون، فاقتلوا المشركين المحاربين الناكثين حيث وجدتموهم وخذوهم أسرى واحصروهم، فإن تابوا وأقاموا الصلاة وآتوا الزكاة فخلوا سبيلهم."
                else -> null
            }

            // Surah 67: Al-Mulk
            67 -> when (ayahNumber) {
                1 -> "تكاثر خير الله وبركته، وعظم سلطانه الذي بيده وحده ملك السماوات والأرض والتصرف فيهما، وهو على كل شيء قدير لا يعجزه أمر."
                2 -> "الذي أوجد الموت وأوجد الحياة ليختبركم ويبتليكم: أيكم أخلص عملاً وأصوبه لله تعالى، وهو العزيز القاهر الغالب، الغفور لذنوب من تاب وأناب من عباده."
                3 -> "الذي خلق سبع سماوات طباقاً كل سماء فوق الأخرى بإحكام بديع، ما ترى في خلق الرحمن من خلل ولا تفاوت، فارجع البصر إلى السماء هل ترى فيها من شقوق أو تصدع؟"
                4 -> "ثم كرر النظر كرة بعد كرة، يرجع إليك بصرك خاسئاً ذليلاً كليلاً عاجزاً عن أن يرى أي عيب أو نقص في خلق الله."
                5 -> "ولقد زيّنا السماء الدنيا بالكواكب والنجوم المضيئة، وجعلناها رجوماً للشياطين المسترقين للسمع، وأعتدنا لهم في الآخرة عذاب السعير."
