                else -> null
            }

            // Surah 18: Al-Kahf
            18 -> when (ayahNumber) {
                1 -> "الحمد لله الذي أنزل على عبده محمد صلى الله عليه وسلم الكتاب (القرآن) ولم يجعل فيه اعوجاجاً ولا تناقضاً."
