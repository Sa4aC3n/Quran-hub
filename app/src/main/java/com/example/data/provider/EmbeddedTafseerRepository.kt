                2 -> "الثناء والشكر والحمد الكامل لله تعالى وحده، المستحق للعبادة، رب العالمين وخالقهم ورازقهم ومدبر أمورهم."
                3 -> "ذو الرحمة الواسعة الشاملة لجميع المخلوقات، والرحيم الخاص بالمؤمنين يوم القيامة."
                4 -> "المالك المتصرف ليوم الحساب والجزاء، وهو يوم القيامة حيث لا ملك لأحد غيره سبحانه."
                5 -> "نخصك وحدك يا ربنا بالعبادة والطاعة، ونخصك وحدك بالاستعانة في جميع أمورنا الدينية والدنيوية."
